"""Generate the Markdown command reference (``docs/cli.md``) from the argparse tree.

Run ``python -m yourls_manager.clidoc`` after changing commands or their help texts;
``--check`` exits 1 when the file is stale (``tests/test_clidoc.py`` does the same).
The help strings and descriptions in ``cli.py`` are the documentation.
"""

from __future__ import annotations

import argparse
import functools
import sys
from collections.abc import Iterator, Sequence
from pathlib import Path

from .cli import build_parser

DEFAULT_OUT = Path("docs/cli.md")
WIDTH = 100
# Global options are listed once at the top, not under every command.
GLOBAL_DESTS = {"site_dir", "verbose", "help", "version"}
GLOBAL_USAGE = "[-h] [--site-dir PATH] [-v]"

HEADER = """\
# ym command reference

<!-- Generated by `python -m yourls_manager.clidoc` from the help texts in cli.py. Do not edit. -->

"""


def _subcommands(
    parser: argparse.ArgumentParser,
) -> Iterator[tuple[str, str, argparse.ArgumentParser]]:
    """(name, help, parser) for each visible subcommand, in definition order."""
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            for choice in action._choices_actions:  # only those with help=
                yield choice.dest, choice.help or "", action.choices[choice.dest]


def _fix_width(parser: argparse.ArgumentParser) -> None:
    parser.formatter_class = functools.partial(argparse.HelpFormatter, width=WIDTH)
    parser.color = False  # Python 3.14+ colors help text
    for _, _, sub in _subcommands(parser):
        _fix_width(sub)


def _invocation(formatter: argparse.HelpFormatter, action: argparse.Action) -> str:
    """``-m, --message MESSAGE`` on every Python (before 3.13 argparse repeats the metavar)."""
    if not action.option_strings:
        if action.metavar is not None:
            return str(action.metavar)
        if action.choices is not None:
            return "{" + ",".join(map(str, action.choices)) + "}"
        return action.dest
    names = ", ".join(action.option_strings)
    if action.nargs == 0:
        return names
    return f"{names} {formatter._format_args(action, action.dest.upper())}"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _options(parser: argparse.ArgumentParser, *, skip: set[str]) -> list[str]:
    formatter = parser._get_formatter()
    out: list[str] = []
    for group in parser._action_groups:
        rows = []
        for action in group._group_actions:
            if action.help == argparse.SUPPRESS or action.dest in skip:
                continue
            if isinstance(action, argparse._SubParsersAction):
                continue
            invocation = _invocation(formatter, action)
            text = formatter._expand_help(action) if action.help else ""
            rows.append(f"| `{_cell(invocation)}` | {_cell(text)} |")
        if rows:
            title = (group.title or "options").capitalize()
            column = "Argument" if group.title == "positional arguments" else "Option"
            out += [f"**{title}**", "", f"| {column} | Description |", "|---|---|", *rows, ""]
    return out


def _epilog(parser: argparse.ArgumentParser) -> list[str]:
    # Epilogs in cli.py are preformatted blocks (examples, environment, exit codes).
    return ["```", parser.epilog.rstrip(), "```", ""] if parser.epilog else []


def _command(parser: argparse.ArgumentParser, summary: str, level: int) -> list[str]:
    out = [f"{'#' * level} {parser.prog}", ""]
    if summary:
        out += [summary[0].upper() + summary[1:] + ".", ""]
    usage = parser.format_usage().removeprefix("usage: ").rstrip()
    usage = usage.replace(f"{parser.prog} {GLOBAL_USAGE}", parser.prog, 1)
    usage = usage.replace("\n" + " " * len("usage: "), "\n")
    out += ["```", usage, "```", ""]
    if parser.description:
        out += [" ".join(parser.description.split()), ""]
    out += _options(parser, skip=GLOBAL_DESTS)
    out += _epilog(parser)
    subs = list(_subcommands(parser))
    if subs:
        out += ["| Command | Description |", "|---|---|"]
        out += [f"| `{sub.prog}` | {_cell(help_)} |" for _, help_, sub in subs]
        out.append("")
        for _, help_, sub in subs:
            out += _command(sub, help_, level + 1)
    return out


def generate() -> str:
    parser = build_parser()
    _fix_width(parser)
    lines = [HEADER.rstrip("\n"), ""]
    if parser.description:
        lines += [parser.description, ""]
    lines += ["## Global options", ""]
    globals_ = {a.dest for a in parser._actions} - GLOBAL_DESTS
    lines += _options(parser, skip=globals_ | {"help"})
    lines += _epilog(parser)
    lines += ["## Commands", "", "| Command | Description |", "|---|---|"]
    subs = list(_subcommands(parser))
    lines += [f"| [`{sub.prog}`](#{_anchor(sub.prog)}) | {_cell(h)} |" for _, h, sub in subs]
    lines.append("")
    for _, help_, sub in subs:
        lines += _command(sub, help_, 2)
    return "\n".join(lines).rstrip("\n") + "\n"


def _anchor(heading: str) -> str:
    return heading.lower().replace(" ", "-")


def main(argv: Sequence[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m yourls_manager.clidoc", description=__doc__)
    p.add_argument("out", nargs="?", type=Path, default=DEFAULT_OUT)
    p.add_argument("--check", action="store_true", help="exit 1 if OUT is not up to date")
    args = p.parse_args(argv)
    text = generate()
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else None
        if current != text:
            print(f"{args.out} is stale; run `python -m yourls_manager.clidoc`", file=sys.stderr)
            return 1
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
